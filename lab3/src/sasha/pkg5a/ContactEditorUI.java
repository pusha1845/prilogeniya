    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
                                                                                                                                                               
        try {
            String upperText = jTextFieldLowerLabel.getText();    // верхний предел
            String lowerText = jTextFieldLowerInput.getText();    // нижний предел
            String stepText = jTextFieldStepInput.getText();      // шаг
            
            double upper = Double.parseDouble(upperText);
            double lower = Double.parseDouble(lowerText);
            double step = Double.parseDouble(stepText);
            
            RecIntegral record = new RecIntegral(lower, upper, step);
            integralRecords.add(record);
            
            DefaultTableModel tModel = (DefaultTableModel) jTable1.getModel();
            tModel.addRow(new Object[]{record.getHighLimit(), record.getLowerLim(), record.getStep()});  
            
            // Очищаем поля
            jTextFieldLowerLabel.setText("");
            jTextFieldLowerInput.setText("");
            jTextFieldStepInput.setText("");
            
            JOptionPane.showMessageDialog(this, "Запись добавлена!", "Успех", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Введите корректные числа!\nИспользуйте точку (.) для десятичных дробей.", 
                "Ошибка формата", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Ошибка параметров", JOptionPane.ERROR_MESSAGE);
        } catch (InvalideRangeException e) {
            JOptionPane.showMessageDialog(this, e.getMessage() + "\nЗначение: " + e.getInvalidValue(), 
                "Ошибка диапазона", JOptionPane.ERROR_MESSAGE);
        }
    

    


    }//GEN-LAST:event_jButtonAddActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
                                              
    int selectedRow = jTable1.getSelectedRow();
    
    if (selectedRow != -1) {
        int confirm = JOptionPane.showConfirmDialog(this, "Удалить выбранную строку?", "Подтверждение", JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            DefaultTableModel tModel = (DefaultTableModel) jTable1.getModel();
            tModel.removeRow(selectedRow);
            
            if (selectedRow < integralRecords.size()) {
                integralRecords.remove(selectedRow);
            }
            
            JOptionPane.showMessageDialog(this, "Строка удалена!", "Успех", JOptionPane.INFORMATION_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Выберите строку для удаления!", "Предупреждение", JOptionPane.WARNING_MESSAGE);
    }

 

    }//GEN-LAST:event_jButtonDeleteActionPerformed

    private void jButtonSolveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSolveActionPerformed
                                                                                                                            
        int selectedRow = jTable1.getSelectedRow();
        
        if (selectedRow != -1) {
            try {
                double upper = Double.parseDouble(jTable1.getValueAt(selectedRow, 0).toString());
                double lower = Double.parseDouble(jTable1.getValueAt(selectedRow, 1).toString());
                double step = Double.parseDouble(jTable1.getValueAt(selectedRow, 2).toString());
                
                RecIntegral ri = new RecIntegral(lower, upper, step);
                double integral = ri.calculate(lower, upper, step);
                
                if (selectedRow < integralRecords.size()) {
                    integralRecords.set(selectedRow, ri);
                } else {
                    integralRecords.add(ri);
                }
                
                ri.setResult(integral);
                
                jTable1.setValueAt(String.format("%.6f", integral), selectedRow, 3);
                
                JOptionPane.showMessageDialog(this, "Интеграл вычислен: " + String.format("%.6f", integral), 
                    "Результат", JOptionPane.INFORMATION_MESSAGE);
                
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ошибка формата данных в таблице!\nИспользуйте точку (.) для десятичных дробей.", 
                    "Ошибка формата", JOptionPane.ERROR_MESSAGE);
            } catch (IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Ошибка параметров", JOptionPane.ERROR_MESSAGE);
            } catch (InvalideRangeException e) {
                JOptionPane.showMessageDialog(this, e.getMessage() + "\nЗначение: " + e.getInvalidValue(), 
                    "Ошибка диапазона", JOptionPane.ERROR_MESSAGE);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Ошибка при вычислении: " + e.getMessage(), 
                    "Ошибка", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Выберите строку для вычисления!", 
                "Предупреждение", JOptionPane.WARNING_MESSAGE);
        }
    



    
    }//GEN-LAST:event_jButtonSolveActionPerformed

