    private void jMenuItem1LoadtxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1LoadtxtActionPerformed
    
        JFileChooser f = new JFileChooser();
        javax.swing.filechooser.FileNameExtensionFilter filter = 
            new javax.swing.filechooser.FileNameExtensionFilter("Text file (*.txt)", "txt");
        f.setFileFilter(filter);
        f.showOpenDialog(this);
        
        File file = f.getSelectedFile();
        if (file == null) return;
        
        try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
            List<RecIntegral> loadedRecords = new ArrayList<>();
            String line;
            
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split("\\|");
                if (parts.length >= 3) {
                    double lower = Double.parseDouble(parts[0]);
                    double upper = Double.parseDouble(parts[1]);
                    double step = Double.parseDouble(parts[2]);
                    double result = parts.length >= 4 ? Double.parseDouble(parts[3]) : 0.0;
                    
                    RecIntegral record = new RecIntegral(lower, upper, step);
                    record.setResult(result);
                    loadedRecords.add(record);
                }
            }
            
            integralRecords = loadedRecords;
            updateTableFromCollection();
            JOptionPane.showMessageDialog(this, "Загружено " + loadedRecords.size() + " записей");
            
        } catch (IOException | NumberFormatException | InvalideRangeException ex) {
            JOptionPane.showMessageDialog(this, "Ошибка загрузки: " + ex.getMessage());
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_jMenuItem1LoadtxtActionPerformed

