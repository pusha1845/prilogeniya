    private void updateTableFromCollection() {
    tableModel.setRowCount(0);
    
    for (RecIntegral record : integralRecords) {
        Object[] row = {
            record.getUpperLim(),  // верхний предел
            record.getLowerLim(),  // нижний предел
            record.getStep(),      // шаг
            String.format("%.6f", record.getResult()) // результат
        };
        tableModel.addRow(row);
    }
}
